# Module docstring explaining multi-dialect SQL DDL generation logic
"""Multi-dialect SQL DDL and Rollback SQL generator supporting SQLite, PostgreSQL, Snowflake, BigQuery, and Azure Synapse."""

# Import Tuple and List type hints
from typing import List, Tuple
# Import DimensionSpec and FactSpec contract dataclasses
from dw_agent.contracts import DimensionSpec, FactSpec
# Import ConfigManager for platform profile lookup
from dw_agent.config import ConfigManager

# Master DDL and Rollback generator function
def generate_target_ddl(
    dimensions: List[DimensionSpec],
    facts: List[FactSpec],
    dialect: str = "sqlite",
    config_mgr: ConfigManager = None
) -> Tuple[str, str]:
    """Generate target CREATE TABLE DDL scripts and matching DROP TABLE Rollback DDL scripts for requested dialect.

    Args:
        dimensions (List[DimensionSpec]): Dimension specifications.
        facts (List[FactSpec]): Fact specifications.
        dialect (str, optional): Target SQL dialect (sqlite, postgresql, snowflake, bigquery, synapse). Defaults to "sqlite".
        config_mgr (ConfigManager, optional): Configuration manager instance. Defaults to None.

    Returns:
        Tuple[str, str]: Tuple of (target_ddl_sql_string, rollback_ddl_sql_string).
    """
    if config_mgr is None:
        config_mgr = ConfigManager()

    dialect_clean = dialect.lower().strip()
    profile = config_mgr.load_platform_profile(dialect_clean)
    type_map = config_mgr.get_type_mapping(dialect_clean)
    supports_fk = profile.get("supports_foreign_keys", True)
    
    ddl_lines = []
    rollback_lines = []
    
    ddl_lines.append(f"-- ============================================================")
    ddl_lines.append(f"-- Target Data Warehouse DDL ({dialect_clean.upper()})")
    ddl_lines.append(f"-- Generated by Data Warehouse Design Agent")
    ddl_lines.append(f"-- ============================================================\n")

    rollback_lines.append(f"-- ============================================================")
    rollback_lines.append(f"-- Rollback DDL ({dialect_clean.upper()})")
    rollback_lines.append(f"-- Generated by Data Warehouse Design Agent")
    rollback_lines.append(f"-- ============================================================\n")

    # Dialect-specific surrogate primary key syntax declarations
    sk_definitions = {
        "sqlite": "INTEGER PRIMARY KEY",
        "postgresql": "BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY",
        "snowflake": "NUMBER(38,0) IDENTITY(1,1) PRIMARY KEY",
        "bigquery": "INT64",
        "synapse": "INT IDENTITY(1,1) PRIMARY KEY"
    }
    sk_type = sk_definitions.get(dialect_clean, profile.get("surrogate_key_type", "INTEGER PRIMARY KEY"))

    # Track view drop statements for clean rollback order
    view_rollback = []

    # 1. Generate Dimension Table DDL statements
    for d in dimensions:
        tbl = d.table_name
        rollback_lines.append(f"DROP TABLE IF EXISTS {tbl};")
        
        ddl_lines.append(f"CREATE TABLE {tbl} (")
        col_defs = []
        
        # Surrogate Primary Key
        col_defs.append(f"    {d.surrogate_key} {sk_type}")
        
        # Business Key and Attribute Columns
        for c in d.columns:
            base_type = c.data_type.split("(")[0].upper()
            mapped_type = type_map.get(base_type, c.data_type)
            # Re-attach type parameters e.g., VARCHAR(64)
            if "(" in c.data_type and "(" not in mapped_type and mapped_type.upper() in ["VARCHAR", "NVARCHAR", "NUMERIC", "DECIMAL", "NUMBER"]:
                param = c.data_type[c.data_type.find("("):]
                mapped_type = f"{mapped_type}{param}"
            col_defs.append(f"    {c.name} {mapped_type}")
            
        # Standard Audit Timestamp Columns
        if dialect_clean == "bigquery":
            col_defs.append("    dw_created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP()")
            col_defs.append("    dw_updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP()")
        else:
            col_defs.append("    dw_created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")
            col_defs.append("    dw_updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")
        
        ddl_lines.append(",\n".join(col_defs))
        ddl_lines.append(");\n")

        # Unknown Member (-1 / 'UNKNOWN') Insert Statement
        ddl_lines.append(f"-- Insert Default Unknown Member for {tbl}")
        if dialect_clean == "sqlite":
            ddl_lines.append(f"INSERT OR IGNORE INTO {tbl} ({d.surrogate_key}, {d.business_key}) VALUES (-1, 'UNKNOWN');\n")
        else:
            ddl_lines.append(f"INSERT INTO {tbl} ({d.surrogate_key}, {d.business_key}) VALUES (-1, 'UNKNOWN');\n")

        # Create Active View for SCD Type 2 Dimensions
        if d.is_scd2 or any(c.name == "is_current" for c in d.columns):
            view_name = f"v_{tbl}_current"
            view_rollback.append(f"DROP VIEW IF EXISTS {view_name};")
            ddl_lines.append(f"-- View for current SCD2 records on {tbl}")
            if dialect_clean == "bigquery":
                ddl_lines.append(f"CREATE OR REPLACE VIEW {view_name} AS SELECT * FROM {tbl} WHERE is_current = TRUE;\n")
            else:
                ddl_lines.append(f"CREATE VIEW {view_name} AS SELECT * FROM {tbl} WHERE is_current = 1;\n")

    # 2. Generate Fact Table DDL statements
    for f in facts:
        tbl = f.table_name
        rollback_lines.append(f"DROP TABLE IF EXISTS {tbl};")

        ddl_lines.append(f"CREATE TABLE {tbl} (")
        col_defs = []

        # Fact Table Primary Key
        col_defs.append(f"    {tbl}_id {sk_type}")

        # Foreign Keys referencing Dimension Surrogate Keys
        fk_type = type_map.get("INTEGER", "INT") if dialect_clean != "bigquery" else "INT64"
        for fk in f.foreign_keys:
            col_defs.append(f"    {fk['col']} {fk_type} NOT NULL")

        # Degenerate Dimensions (e.g. order_id, account_number)
        string_type = type_map.get("VARCHAR", "VARCHAR(64)")
        for dg in f.degenerate_dimensions:
            col_defs.append(f"    {dg} {string_type}")

        # Measures (Numeric/Decimal metrics)
        numeric_type = type_map.get("DECIMAL", "NUMERIC(18,2)")
        for m in f.measures:
            col_defs.append(f"    {m.name} {numeric_type}")

        # Audit Timestamp Columns
        if dialect_clean == "bigquery":
            col_defs.append("    dw_created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP()")
            col_defs.append("    dw_updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP()")
        else:
            col_defs.append("    dw_created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")
            col_defs.append("    dw_updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")

        # Foreign Key Constraints for supported RDBMS platforms
        if supports_fk and dialect_clean not in ["bigquery"]:
            for fk in f.foreign_keys:
                target_dim = fk.get("target_dim")
                target_sk = fk.get("col")
                if target_dim and target_sk:
                    col_defs.append(f"    CONSTRAINT fk_{tbl}_{target_dim} FOREIGN KEY ({target_sk}) REFERENCES {target_dim}({target_sk})")

        ddl_lines.append(",\n".join(col_defs))
        ddl_lines.append(");\n")

    # Combine Rollback DDL: Views dropped first before dropping tables
    full_rollback = view_rollback + rollback_lines

    target_sql = "\n".join(ddl_lines)
    rollback_sql = "\n".join(full_rollback)

    return target_sql, rollback_sql


