"""Multi-dialect SQL DDL and Rollback SQL generator."""

from typing import List, Tuple
from dw_agent.contracts import DimensionSpec, FactSpec
from dw_agent.config import ConfigManager

def generate_target_ddl(
    dimensions: List[DimensionSpec],
    facts: List[FactSpec],
    dialect: str = "sqlite",
    config_mgr: ConfigManager = None
) -> Tuple[str, str]:
    if config_mgr is None:
        config_mgr = ConfigManager()

    profile = config_mgr.load_platform_profile(dialect)
    type_map = config_mgr.get_type_mapping(dialect)
    
    ddl_lines = []
    rollback_lines = []
    
    ddl_lines.append(f"-- ============================================================")
    ddl_lines.append(f"-- Target Data Warehouse DDL ({dialect.upper()})")
    ddl_lines.append(f"-- Generated by Data Warehouse Design Agent")
    ddl_lines.append(f"-- ============================================================\n")

    rollback_lines.append(f"-- ============================================================")
    rollback_lines.append(f"-- Rollback DDL ({dialect.upper()})")
    rollback_lines.append(f"-- ============================================================\n")

    sk_type = profile.get("surrogate_key_type", "INTEGER PRIMARY KEY")

    # Generate Dimensions
    for d in dimensions:
        tbl = d.table_name
        rollback_lines.append(f"DROP TABLE IF EXISTS {tbl};")
        
        ddl_lines.append(f"CREATE TABLE {tbl} (")
        col_defs = []
        
        # Surrogate key
        col_defs.append(f"    {d.surrogate_key} {sk_type}")
        
        # Business key and attribute columns
        for c in d.columns:
            mapped_type = type_map.get(c.data_type.split("(")[0].upper(), c.data_type)
            col_defs.append(f"    {c.name} {mapped_type}")
            
        # Audit columns
        col_defs.append("    dw_created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")
        col_defs.append("    dw_updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")
        
        ddl_lines.append(",\n".join(col_defs))
        ddl_lines.append(");\n")

        # Unknown member insert for dimensions
        ddl_lines.append(f"-- Insert Default Unknown Member for {tbl}")
        if dialect == "sqlite":
            ddl_lines.append(f"INSERT OR IGNORE INTO {tbl} ({d.surrogate_key}, {d.business_key}) VALUES (-1, 'UNKNOWN');\n")
        else:
            ddl_lines.append(f"INSERT INTO {tbl} ({d.surrogate_key}, {d.business_key}) VALUES (-1, 'UNKNOWN');\n")

    # Generate Facts
    for f in facts:
        tbl = f.table_name
        rollback_lines.append(f"DROP TABLE IF EXISTS {tbl};")

        ddl_lines.append(f"CREATE TABLE {tbl} (")
        col_defs = []

        # Surrogate PK for fact
        col_defs.append(f"    {tbl}_id {sk_type}")

        # FKs
        for fk in f.foreign_keys:
            col_defs.append(f"    {fk['col']} INTEGER NOT NULL")

        # Degenerate dimensions
        for dg in f.degenerate_dimensions:
            col_defs.append(f"    {dg} VARCHAR(64)")

        # Measures
        for m in f.measures:
            col_defs.append(f"    {m.name} NUMERIC(18,2)")

        # Audit columns
        col_defs.append("    dw_created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")
        col_defs.append("    dw_updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")

        ddl_lines.append(",\n".join(col_defs))
        ddl_lines.append(");\n")

    target_sql = "\n".join(ddl_lines)
    rollback_sql = "\n".join(rollback_lines)

    return target_sql, rollback_sql
