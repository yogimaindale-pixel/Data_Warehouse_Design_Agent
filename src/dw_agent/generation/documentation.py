"""Documentation generator for executive summary, traceability, ADRs, performance, and review package."""

from typing import List, Dict, Any
from dw_agent.contracts import DimensionSpec, FactSpec, Requirement

def generate_executive_summary(
    dimensions: List[DimensionSpec],
    facts: List[FactSpec],
    requirements: List[Requirement],
    validation_passed: bool
) -> str:
    status_str = "ACCEPTED & PASS" if validation_passed else "REVIEW REQUIRED / BLOCKED"
    lines = []
    lines.append("# Executive Summary: Data Warehouse Design Package\n")
    lines.append(f"**Overall Package Status**: `{status_str}`")
    lines.append(f"**Total Requirements Discovered**: {len(requirements)}")
    lines.append(f"**Total Dimension Tables Designed**: {len(dimensions)}")
    lines.append(f"**Total Fact Tables Designed**: {len(facts)}\n")
    lines.append("## Core Architectural Highlights")
    lines.append("- **Conformed Dimensions**: Standardized across business processes to enable enterprise drill-across analytical reporting.")
    lines.append("- **Explicit Grain Declaration**: Every fact table enforces a strict single-sentence grain rule.")
    lines.append("- **Deterministic Governance**: Every decision is evidence-backed and validated against dimensional rules.")
    lines.append("- **Multi-Dialect DDL**: Physical SQL generated for SQLite, PostgreSQL, Snowflake, BigQuery, and Synapse.\n")
    return "\n".join(lines)

def generate_security_doc() -> str:
    return """# Security & Privacy Design Considerations

## 1. PII & Sensitive Data Governance
- Candidate PII columns are automatically detected via configurable name patterns (`email`, `ssn`, `phone`, `credit_card`, `address`, `first_name`, `last_name`).
- Raw source PII columns are tagged for masking or column-level access control in target data marts.
- Sample outputs generated by the DW Design Agent never contain live production credentials or unmasked PII.

## 2. Access Control Principles
- Read-only service accounts for metadata scanning and sample data profiling.
- Role-based Access Control (RBAC) recommended for target dimensional tables:
  - **BI Analysts**: Read access to conformed views excluding PII attributes.
  - **Data Engineers / ETL**: Full read/write access to staging and core warehouse schemas.
  - **Governance Officers**: Audit log read access.
"""

def generate_performance_doc() -> str:
    return """# Performance Design & Optimization Recommendations

## 1. Indexing & Partitioning Strategy
- **Partitioning**: Fact tables partitioned by date key (`date_sk` or `snapshot_date`) to optimize windowed queries and partition pruning.
- **Clustering**: Snowflake and BigQuery models set clustering keys on high-cardinality dimension FKs (`customer_sk`, `product_sk`).
- **Indexes**: PostgreSQL and SQLite schemas feature B-Tree indexes on foreign keys and surrogate keys.

## 2. Aggregation & Mart Strategy
- Periodic snapshot facts pre-aggregate high-frequency transaction events to ensure fast sub-second dashboard rendering for executive KPIs.
"""

def generate_adrs() -> str:
    return """# Architecture Decision Records (ADR)

## ADR-001: Integer Auto-Increment Surrogate Keys
- **Status**: Approved
- **Context**: Need durable, system-managed surrogate primary keys for dimensional tables across dialects.
- **Decision**: Generate integer auto-increment surrogate keys (`<entity>_sk`) with `-1` reserved for the default unknown member.
- **Consequences**: Fast join performance and complete decoupling from source natural key changes.

## ADR-002: Deterministic Rule Engine Over Unbounded LLM Generation
- **Status**: Approved
- **Context**: Dimensional modeling decisions (grain, keys, SCD policies) require strict auditability and deterministic repeatability.
- **Decision**: All modeling rules, validations, and mappings are executed via deterministic Python rules.
- **Consequences**: 100% reproducible outputs across reruns with clear evidence chains.
"""
